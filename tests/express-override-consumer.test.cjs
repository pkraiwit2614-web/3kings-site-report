'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')

test('live authenticated Express registry consumes only evidence-gated view',()=>{
 const api=read('app/api/materials/express-register/route.ts')
 assert.match(api,/client\.from\('express_register_effective_rows'\)/)
 assert.doesNotMatch(api,/client\.from\('express_register_rows'\)/)
 assert.match(api,/client\.auth\.getUser\(token\)/)
 assert.match(api,/readPermissionSnapshot\(client\)/)
 assert.match(api,/\.eq\('line_seq',0\)/)
 assert.match(api,/\.eq\('state','complete'\)/)
 assert.match(api,/has_verified_project_override,project_evidence_url/)
 assert.match(api,/if\(rowError\)return respond\(\{error:'REGISTER_READ_FAILED'\},503\)/)
})
