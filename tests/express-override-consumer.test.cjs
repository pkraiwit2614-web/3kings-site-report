test('project overlay remains source-safe across batches and two unverified docs remain on HOLD',()=>{
 const sql=read('supabase/migrations/20261029024500_express_project_override_read_view.sql')
 assert.match(sql,/security_invoker=true/)
 assert.match(sql,/from public\.express_register_rows r/)
 assert.match(sql,/create table if not exists public\.express_project_overrides/)
 assert.match(sql,/\('PO_PL','PL0000976',array\['CONDO-B'\]/)
 assert.match(sql,/\('PO_PL','PL0000850',array\['PROUD-KARON'\]/)
 assert.doesNotMatch(sql,/\('PO_PL','PL0000973',array/)
 assert.doesNotMatch(sql,/\('PR_PC','PO691027002',array/)
 assert.doesNotMatch(sql,/\bupdate public\.express_register_rows\b|\bdelete from public\.express_register_rows\b/i)
})
test('real local Viewer test retains synthetic registry via invoker view, not a bypass',()=>{
 const fixture=read('tests/e2e/local-stack/supabase/seed.sql')
 assert.match(fixture,/CREATE OR REPLACE VIEW public\.express_register_effective_rows/)
 assert.match(fixture,/WITH \(security_invoker=true\)/)
 assert.match(fixture,/FROM public\.express_register_rows r;/)
 assert.match(fixture,/REVOKE ALL ON public\.express_register_effective_rows FROM PUBLIC, anon/)
 assert.doesNotMatch(fixture,/GRANT ALL ON public\.express_register_effective_rows TO anon/)
})
