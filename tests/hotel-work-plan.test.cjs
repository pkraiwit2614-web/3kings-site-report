const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=p=>fs.readFileSync(p,'utf8')
const sql=read('supabase/migrations/20261014115000_hotel_work_plan_isolated.sql')
const tabs=read('components/AppShell.tsx')
const access=read('lib/accessControl.ts')
const work=read('app/hotel-work-plan/page.tsx')
const defect=read('app/defects/page.tsx')
test('Hotel Work Plan seed preserves every source schedule entry and GOOD aliases',()=>{
 const entries=[...sql.matchAll(/\((\d+),(\d+),'([^']+)','([AB]\d{3})',(\d+)\)/g)]
 assert.equal(entries.length,267)
 assert.deepEqual(entries.map(m=>Number(m[1])),Array.from({length:267},(_,i)=>i+1))
 assert.deepEqual(entries.map(m=>Number(m[2])).reduce((acc,n)=>(acc[n]=(acc[n]||0)+1,acc),{}),Object.fromEntries(Array.from({length:9},(_,i)=>[i+1,i===8?27:30])))
 assert.equal(Number(entries[0][5]),5);assert.equal(Number(entries.at(-1)[5]),271)
 for(let k=1;k<=5;k++)assert.ok(entries.some(m=>m[3]==='GOOD 0'+k&&m[4]==='B10'+k))
 assert.doesNotMatch(sql,/UPDATE public\.condo_room_status|DELETE FROM public\.condo_room_status/i)
 assert.doesNotMatch(sql,/UPDATE public\.hotel_room_availability|DELETE FROM public\.hotel_room_availability/i)
})
test('tab order, visibility, and scoped editor access remain consistent',()=>{
 const matches=[...tabs.matchAll(/<Link href="\/(defect-flow|defects|hotel-work-plan|hotel-room-status)" className/g)].map(x=>x[1])
 assert.deepEqual(matches,['defect-flow','defects','hotel-work-plan','hotel-room-status'])
 assert.match(tabs,/>Defect Flow<\/Link>/)
 assert.match(tabs,/>Work Plan<\/Link>/)
 assert.match(tabs,/>Status \| OOO\/OOS<\/Link>/)
 assert.match(access,/value==='\/hotel-work-plan'/)
 assert.match(work,/role==='owner'\|\|role==='defect_editor'/)
 assert.match(sql,/p\.role='defect_editor'/)
 assert.doesNotMatch(work,/from\('condo_room_status'\)\.update/)
})
