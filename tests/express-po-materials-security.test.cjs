'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const read=path=>fs.readFileSync(require('node:path').join(process.cwd(),path),'utf8')
test('Express PO display never reads data directly from browser or writes existing registers',()=>{
 const page=read('app/materials/page.tsx')
 const component=read('components/ExpressPoSection.tsx')
 const route=read('app/api/materials/express-po/route.ts')
 assert.match(page,/<ExpressPoSection /)
 assert.match(component,/getSupabase/)
 assert.match(component,/getSession/)
 assert.match(component,/Authorization:'Bearer '/)
 assert.match(component,/receiptEvidence/)
 assert.match(route,/EXPRESS_PO_DISPLAY_ENABLED/)
 assert.match(route,/client\.auth\.getUser\(token\)/)
 assert.match(route,/readPermissionSnapshot/)
 assert.match(route,/grant\.level==='none'/)
 assert.match(route,/canAccessPath\(role,'\/materials',matrix\)/)
 assert.match(route,/exchangeVercelOidcToken/)
 assert.match(route,/cache-control':'private, no-store/)
 assert.match(route,/Express_PO_Preview_Staging_2026-10-19/)
 assert.doesNotMatch(route,/(\.insert\(|\.upsert\(|\.update\(|\.delete\(|\.rpc\('express_po_stage_import')/)
 assert.doesNotMatch(component,/docs\.google\.com|drive\.google\.com|supabase\.co\/rest\/v1/)
})
test('Preview import retains stage-only, no production or cron',()=>{
 const r=read('app/api/sync/express-po/route.ts')
 const sheet=read('lib/express-po/sheets-sync.ts')
 assert.match(r,/process\.env\.VERCEL_ENV!=='preview'/)
 assert.match(r,/EXPRESS_PO_SYNC_SECRET/)
 assert.match(r,/stageExpressInSheets/)
 assert.doesNotMatch(r,/SUPABASE_SERVICE_ROLE_KEY|createClient/)
 assert.match(sheet,/EXPRESS_PO_ALLOW_STAGING_WRITE/)
 assert.match(sheet,/ALREADY_STAGED_NO_WRITE/)
 assert.match(sheet,/SHEETS_READBACK_MISMATCH/)
 assert.doesNotMatch(sheet,/\.supabase\.co/)
})
