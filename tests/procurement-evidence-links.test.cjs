const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'..')
const read=p=>fs.readFileSync(path.join(root,p),'utf8')
const procurement=read('app/procurement/page.tsx')
const materials=read('app/materials/page.tsx')
const ui=read('components/ProcurementEvidenceLinks.tsx')
const logic=read('lib/procurementEvidence.ts')
const migration=read('supabase/migrations/20261022074048_procurement_evidence_links_readonly.sql')

// Read only: no changes to existing procurement status, payment, delivery or material records.
assert.match(procurement,/from\('procurement_items'\)\.select\('\*'\)/)
assert.match(materials,/from\('v_procurement_items'\)\.select\('\*'\)/)
assert.match(procurement,/requireSuccessfulReads\(\[r,links,p,checked,imported\]\)/)
assert.match(materials,/requireSuccessfulReads\(\[p,m,pr,prLinks,t,overrides,checked,imported\]\)/)
for(const source of [procurement,materials]){
  assert.match(source,/from\('procurement_evidence_links'\)/)
  assert.match(source,/evidence\.error\?\[\]/,'Evidence read must be optional when no table/migration')
  assert.match(source,/<ProcurementEvidenceLinks/)
  assert.doesNotMatch(source,/\.from\('procurement_evidence_links'\)\.insert\(/)
}
assert.match(ui,/matchingProcurementEvidence/)
assert.match(ui,/target="_blank" rel="noopener noreferrer"/)
assert.match(ui,/รอหลักฐาน/)
assert.match(ui,/ZIP รวม/)
assert.match(logic,/row\.document_no\.trim\(\)\.toUpperCase\(\)===lookup/,
  'Exact identifier required: never fuzzy-link procurement documents')
assert.match(logic,/if\(column==='pr'\)return 'PR'/)
assert.match(logic,/return \/\^PL/)
assert.match(logic,/drive\.google\.com\/file\/d/)
assert.match(migration,/enable row level security/)
assert.match(migration,/private\.matrix_allowed\('procurement'::text,'view'::text/)
assert.match(migration,/revoke all on public\.procurement_evidence_links from PUBLIC, anon, authenticated/)
assert.match(migration,/grant select on public\.procurement_evidence_links to authenticated/)
assert.doesNotMatch(migration,/grant (insert|update|delete|all) on public\.procurement_evidence_links to authenticated/i)
assert.doesNotMatch(migration,/insert into public\.procurement_evidence_links/i,
  'No private Drive file IDs in public SQL migration')
console.log('Procurement evidence gate: PASS — exact match, auth-bound optional read, no write/status changes')
