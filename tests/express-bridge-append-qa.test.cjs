'use strict'
const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const vm=require('node:vm')
const path=require('node:path')
const source=fs.readFileSync(path.join(__dirname,'../docs/apps-script/ExpressBridgeAppendSafeQA_2026-10-22.gs'),'utf8')
const ctx=vm.createContext({})
vm.runInContext(source,ctx,{filename:'ExpressBridgeAppendSafeQA_2026-10-22.gs'})
test('pure QA worksheet data is synthetic and XML-escaped',()=>{
 const xml=ctx.expressBridgeAppendQASheetXml_([['Doc','Note'],['QA-ONLY','=HYPERLINK("x&y") <TEST>']])
 assert.match(xml, /<sheetData>/)
 assert.match(xml, /&lt;TEST&gt;/)
 assert.match(xml, /&amp;/)
 assert.match(xml, /&quot;/)
 assert.doesNotMatch(xml, /<f>/)
})
test('QA rejects ambiguous XML and never changes original Master',()=>{
 assert.equal(ctx.expressBridgeAppendQAExpected_().length,2)
 const out=ctx.expressBridgeAppendQAOnlyOnce_('<x:sheets></x:sheets>','</x:sheets>','<x:sheet />','test')
 assert.equal(out,'<x:sheets><x:sheet /></x:sheets>')
 assert.throws(()=>ctx.expressBridgeAppendQAOnlyOnce_('no close','</x:sheets>','<x:sheet />','test'),/XML_INSERTION_ANCHOR_NOT_UNIQUE/)
 assert.throws(()=>ctx.expressBridgeAppendQAOnlyOnce_('</Types></Types>','</Types>','<Override/>','test'),/XML_INSERTION_ANCHOR_NOT_UNIQUE/)
 assert.match(source, /mutationOriginal:0/)
 assert.match(source, /master\.makeCopy\(/)
})