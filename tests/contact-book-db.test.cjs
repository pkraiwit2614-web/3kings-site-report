const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const api=fs.readFileSync('app/api/contact-book/route.ts','utf8')
const ui=fs.readFileSync('app/contact-book/page.tsx','utf8')
const sql=fs.readFileSync('supabase/migrations/20261021235000_contact_book_directory.sql','utf8')
const legacyDrivePath='lib/contactBookDrive.ts'

test('no Google service account or extra web configuration needed',()=>{
  assert.equal(fs.existsSync(legacyDrivePath),false)
  assert.doesNotMatch(api,/GOOGLE_CONTACT|CONTACT_BOOK_PREVIEW_FILE_ID|getContactCsvDrive|writeContactCsvDrive|driveVerified/)
  assert.match(api,/from\('contact_book_directory'\)/)
  assert.match(api,/rpc\('contact_book_save'/)
  assert.match(ui,/ระบบ Contact Book/)
})
test('all access is authenticated and fail-closed using existing matrix',()=>{
  assert.match(sql,/enable row level security/i)
  assert.match(sql,/revoke all on public\.contact_book_directory from public, anon, authenticated/i)
  assert.match(sql,/grant select on public\.contact_book_directory to authenticated/i)
  assert.doesNotMatch(sql,/grant (update|insert|delete|all) on public\.contact_book_directory to authenticated/i)
  assert.match(sql,/for select to authenticated using \(public\.contact_book_can\('view'\)\)/i)
  assert.match(sql,/where m\.module='contact_book' and m\.role=private\.matrix_role\(\)/)
  assert.match(sql,/not public\.contact_book_can\('manage'\)/)
  assert.match(sql,/grant execute on function public\.contact_book_save\(bigint,text,jsonb\) to authenticated/i)
})
test('writes are serialized and preserve audit, version and existing 41+ rows',()=>{
  assert.match(sql,/jsonb_array_length\(entries\)>=41/)
  assert.match(sql,/where id=1 for update/i)
  assert.match(sql,/v_revision<>p_expected_revision/)
  assert.match(sql,/count\(distinct contact_id\)>1/i)
  assert.match(sql,/insert into private\.contact_book_audit/i)
  assert.match(sql,/jsonb_set\(v_entries/)
  assert.match(sql,/v_entries \|\| jsonb_build_array\(v_after\)/)
  assert.doesNotMatch(sql,/delete from public\.|truncate|drop table public\./i)
})
