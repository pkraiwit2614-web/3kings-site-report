const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const page=fs.readFileSync('app/hotel-work-plan/page.tsx','utf8')

test('All is the initial read-only overview and retains source-day filtering',()=>{
 assert.match(page,/const \[selectedDay,setSelectedDay\]=useState\(0\)/)
 assert.match(page,/selectedDay!==0&&r\.day_no!==selectedDay/)
 assert.match(page,/\{days\.map\(d=>\{/)
 assert.match(page,/key=\{d\.day_no\}/)
 assert.match(page,/<strong>All<\/strong>/)
 assert.match(page,/onClick=\{\(\)=>\{setSelectedDay\(0\);setSelectedSeq\(null\)\}\}/)
 assert.match(page,/const allTotals=dayCounts\.reduce\(/)
 assert.match(page,/rooms:total\.rooms\+d\.rooms,open:total\.open\+d\.open,review:total\.review\+d\.review/)
 assert.match(page,/selectedDay===0\?<div className="work-editor-all">/)
 assert.match(page,/!editable\|\|!day\|\|saving\|\|saveDialog/)
 assert.match(page,/const activePlanRooms=useMemo\(/)
 assert.match(page,/const key=hotelRoomKey\(row\.room_no\)/)
})
