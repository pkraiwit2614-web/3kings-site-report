const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '..')
const read = p => fs.readFileSync(path.join(root, p), 'utf8')
const data = JSON.parse(read('app/defects/common/common-defects-ab-prepared.json'))
const rows = data.rows

test('Common A+B register source completeness, stable IDs and PDF provenance', () => {
  assert.equal(rows.length, 106)
  assert.equal(data.counts.total, 106)
  assert.equal(rows.filter(r => r.building === 'A').length, 58)
  assert.equal(rows.filter(r => r.building === 'B').length, 48)
  assert.equal(new Set(rows.map(r => r.defect_id)).size, 106)
  assert.deepEqual(rows.filter(r => r.building === 'A').map(r => r.defect_id), Array.from({length:58},(_,i)=>'CA-A-'+String(i+1).padStart(3,'0')))
  assert.deepEqual(rows.filter(r => r.building === 'B').map(r => r.defect_id), Array.from({length:48},(_,i)=>'B-COM-'+String(i+1).padStart(3,'0')))
  for (const row of rows) {
    assert.ok(row.location && row.work_description && row.work_type && row.contractor_team)
    assert.ok(row.source_page >= 1)
    assert.match(row.source_file_url, /^https:\/\/drive\.google\.com\//)
    assert.equal(row.status, 'รอตรวจสอบสถานะ')
    assert.equal(row.supervisor, 'บังศักดิ์')
  }
  assert.equal(rows.filter(r=>r.building==='A' && r.contractor_team==='3 Kings').length,40)
  assert.equal(rows.filter(r=>r.building==='A' && r.contractor_team==='ขอพงษ์').length,12)
  assert.equal(rows.filter(r=>r.building==='A' && r.contractor_team==='รอยืนยันผู้รับเหมา').length,6)
})

test('Common displays both buildings, building/work/team/area filters, search, evidence, print', () => {
  const page = read('app/defects/common/page.tsx')
  assert.match(page,/import prepared from '\.\/common-defects-ab-prepared\.json'/)
  assert.match(page,/prepared\.rows\.map/)
  assert.match(page,/building&&row\.building!==building/)
  assert.match(page,/workType&&row\.workType!==workType/)
  assert.match(page,/team&&row\.team!==team/)
  assert.match(page,/area&&row\.area!==area/)
  assert.match(page,/originalEnglish/)
  assert.match(page,/row\.sourceUrl/)
  assert.match(page,/row\.photoFilename/)
  assert.match(page,/window\.print\(\)/)
  assert.match(page,/@media print/)
  assert.match(page,/<DefectReportTabs active="common"\s*\/>/)
  assert.doesNotMatch(page,/\.from\(['"]condo_room_status['"]\)/)
  assert.doesNotMatch(page,/\.insert\(|\.upsert\(|\.update\(|\.delete\(/)
})

test('Condo is still default report and existing source remains unchanged', () => {
  const page = read('app/defects/page.tsx')
  const tabs = read('components/DefectReportTabs.tsx')
  const shell = read('components/AppShell.tsx')
  assert.match(tabs,/href="\/defects"/)
  assert.match(tabs,/href="\/defects\/common"/)
  assert.match(page,/<DefectReportTabs active="condo"\s*\/>/)
  assert.match(page,/from\('condo_room_status'\)/)
  assert.match(shell,/path\.startsWith\('\/defects\/'\)/)
})
